class PointTest(unittest.TestCase):
    """Stored points, read and transformed - or refused, and told why."""

    def setUp(self):
        self.table = cl.DriveTable.from_record(MEASURED_DRIVE)

    def test_it_reads_a_luminance_snapshot(self):
        points = cl.points_from_luminance(SNAPSHOT)
        self.assertEqual(len(points), 4)
        self.assertAlmostEqual(points[0].lux, 0.0202)
        self.assertEqual(points[0].percent, 40)
        self.assertEqual(points[0].hue, 140)
        self.assertEqual(points[0].sat, 0)
        # The clock's own verdict travels with the point, under a name that
        # says whose verdict it is - it was made against the clock's range at
        # the time, and this report may be working to a different one.
        self.assertFalse(points[3].reported_used)
        # Censoring is a question about a range, so it takes one.
        self.assertTrue(points[3].at_ceiling(100))
        self.assertFalse(points[3].at_ceiling(120))
        self.assertTrue(points[2].at_ceiling(60))

    def test_a_point_from_before_the_colour_was_kept_is_unknown_not_red(self):
        doc = {"points": [{"lux": 1.0, "percent": 50, "seconds": 10, "used": True}]}
        point = cl.points_from_luminance(doc)[0]
        self.assertEqual(point.hue, cl.HUE_UNKNOWN)
        self.assertFalse(point.colour_known)
        with self.assertRaises(cl.UnknownColourError):
            cl.transform_point(point, drive=self.table)

    def test_an_unknown_point_can_be_transformed_under_a_stated_assumption(self):
        doc = {"points": [{"lux": 1.0, "percent": 50, "seconds": 10, "used": True}]}
        point = cl.points_from_luminance(doc)[0]
        moved = cl.transform_point(point, drive=self.table, assume=(0, 0))
        self.assertTrue(moved.assumed_colour)
        # And it is the same number the assumption would give if it had been
        # stored - the assumption changes provenance, not arithmetic.
        known = cl.Point(lux=1.0, percent=50, hue=0, sat=0, seconds=10)
        self.assertAlmostEqual(moved.z, cl.transform_point(known, drive=self.table).z)

    def test_the_transform_is_log_lux_against_log_output(self):
        point = cl.Point(lux=0.6225, percent=60, hue=140, sat=0, seconds=1)
        moved = cl.transform_point(point, drive=self.table)
        import math
        self.assertAlmostEqual(moved.x, math.log10(0.6225), places=9)
        self.assertAlmostEqual(
            moved.z,
            cl.log10_output(cl.relative_photopic_output(140, 0, 60, drive=self.table)),
            places=9)

    def test_the_lux_floor_is_the_firmware_floor(self):
        # `Luminance::logLux()` floors at LUX_FLOOR (0.01, LightSensor.h) so a
        # dark room is a number rather than minus infinity. A different floor
        # here would move every dark point.
        self.assertAlmostEqual(cl.LUX_FLOOR, 0.01)
        point = cl.Point(lux=0.0, percent=20, hue=0, sat=0, seconds=1)
        self.assertAlmostEqual(cl.transform_point(point, drive=self.table).x, -2.0, places=9)

    def test_a_white_point_transforms_whatever_hue_was_stored_beside_it(self):
        # The four points this clock has were taught at sat=0, so they carry no
        # colour information and can be re-used as they are. That is the whole
        # reason the existing calibration survives this change.
        first = cl.transform_point(
            cl.Point(lux=1.0, percent=45, hue=0, sat=0, seconds=1), drive=self.table)
        second = cl.transform_point(
            cl.Point(lux=1.0, percent=45, hue=300, sat=0, seconds=1), drive=self.table)
        self.assertEqual(first.z, second.z)


class FitTest(unittest.TestCase):
    """`Luminance::fit()` - least squares, both halves, and its three guards."""

    def test_it_reproduces_the_line_the_clock_fitted(self):
        # The three points and the least-squares column CLAUDE.md records for
        # them. The firmware works in float32 through log10f, so the last
        # digit differs; the line does not.
        import math
        points = [cl.Point(lux=0.0202, percent=40, hue=140, sat=0),
                  cl.Point(lux=0.0507, percent=30, hue=140, sat=0),
                  cl.Point(lux=0.6225, percent=60, hue=140, sat=0)]
        xs = [cl.log_lux(p.lux) for p in points]
        line = cl.fit_line(xs, [p.percent for p in points])
        self.assertTrue(line.fitted)
        self.assertAlmostEqual(line.slope, 16.4178, places=1)
        for x, expected in zip(xs, (33.01, 39.56, 57.44)):
            self.assertAlmostEqual(line.at(x), expected, places=1)

    def test_too_little_spread_moves_the_level_and_keeps_the_slope(self):
        # Ten corrections made in one evening say nothing about steepness;
        # least squares through them is noise multiplied by a large number.
        # Below LUM_FIT_MIN_DECADES the slope stands and only the level moves -
        # which is exactly what the old "shift the whole curve" did, done only
        # when it is all one can honestly do.
        self.assertAlmostEqual(cl.LUM_FIT_MIN_DECADES, 0.6)
        xs = [0.0, 0.1, 0.2]
        line = cl.fit_line(xs, [30.0, 55.0, 40.0], keep_slope=25.0)
        self.assertFalse(line.fitted)
        self.assertAlmostEqual(line.slope, 25.0)
        # Through the centroid, whatever the slope turned out to be.
        self.assertAlmostEqual(line.at(0.1), sum([30.0, 55.0, 40.0]) / 3.0, places=6)

    def test_a_slope_of_zero_or_less_is_refused(self):
        # Darker room, brighter clock is not a thing anybody wants, and one
        # careless nudge in daylight produces it.
        line = cl.fit_line([-2.0, 0.0, 1.0], [80.0, 50.0, 20.0], keep_slope=25.0)
        self.assertFalse(line.fitted)
        self.assertAlmostEqual(line.slope, 25.0)

    def test_the_ceiling_is_censored_and_the_floor_is_not(self):
        # The ceiling is what the hardware can do; the floor is a number the
        # owner chose as the dimmest they ever want, so a point sitting on it
        # is a preference being met rather than a wish being cut off.
        points = [cl.Point(lux=0.02, percent=20, hue=0, sat=0),
                  cl.Point(lux=1.0, percent=60, hue=0, sat=0),
                  cl.Point(lux=9.0, percent=100, hue=0, sat=0)]
        used = cl.censor(points, min_percent=20, max_percent=100)
        self.assertEqual(used, [True, True, False])

    def test_censoring_gives_way_rather_than_leaving_nothing_to_fit(self):
        # Two points at the ceiling and nothing else is a poor line, and no
        # line at all is worse.
        points = [cl.Point(lux=1.0, percent=100, hue=0, sat=0),
                  cl.Point(lux=9.0, percent=100, hue=0, sat=0)]
        self.assertEqual(cl.censor(points, 20, 100), [True, True])


class CompareTest(unittest.TestCase):
    """The offline question: is the new coordinate better on the real data?"""

    def setUp(self):
        self.table = cl.DriveTable.from_record(MEASURED_DRIVE)

    def report(self, snapshot=None, **kwargs):
        return cl.compare(snapshot or SNAPSHOT, drive=self.table, **kwargs)

    def test_it_carries_the_optical_stack_it_was_measured_on(self):
        # The stack is part of the photometry: a diffuser in front of the mask
        # rather than behind it is a different device, and a dataset that does
        # not say which one it came from cannot be compared with another.
        self.assertEqual(cl.STACK_ID_DEFAULT, "current-diffuser-before-mask")
        self.assertEqual(self.report()["stackId"], "current-diffuser-before-mask")
        self.assertEqual(self.report(stack_id="mask-then-wh73")["stackId"], "mask-then-wh73")

    def test_it_fits_both_models_on_the_same_points(self):
        report = self.report()
        # The current model, in percent, is what the clock is doing today.
        self.assertAlmostEqual(report["percentFit"]["slope"], 16.4178, places=1)
        # The proposed one, in log relative output. Both fitted from the same
        # three usable points, so the comparison is like for like.
        self.assertTrue(report["outputFit"]["fitted"])
        self.assertEqual(report["percentFit"]["count"], 3)
        self.assertEqual(report["outputFit"]["count"], 3)

    def test_every_point_gets_a_residual_in_both_coordinates(self):
        report = self.report()
        self.assertEqual(len(report["points"]), 4)
        first = report["points"][0]
        self.assertIn("percentResidual", first)     # percentage points
        self.assertIn("outputResidual", first)      # decades
        # And what the new model would have shown at that light, so the two
        # can be compared in the unit the owner actually sees.
        self.assertIn("predictedPercent", first)

    def test_the_ceiling_point_is_censored_in_both_and_says_so(self):
        report = self.report()
        ceiling = report["points"][3]
        self.assertTrue(ceiling["censored"])
        self.assertFalse(ceiling["usedInPercentFit"])
        self.assertFalse(ceiling["usedInOutputFit"])
        self.assertTrue(any("censored" in w for w in report["warnings"]))

    def test_a_ceiling_point_is_censored_even_when_the_snapshot_says_used(self):
        # `used` in a /luminance answer is the *clock's* verdict, made against
        # the clock's own range at the time it was written. This report fits
        # its own lines, possibly over a range given on the command line, so
        # membership has to be recomputed - a stale flag saying "used" must not
        # let a ceiling point into the fit as an equality.
        snapshot = {"minPercent": 20, "maxPercent": 100, "slope": 16.0, "points": [
            {"used": True, "lux": 0.02, "percent": 30, "hue": 140, "sat": 0},
            {"used": True, "lux": 0.60, "percent": 55, "hue": 140, "sat": 0},
            {"used": True, "lux": 9.00, "percent": 100, "hue": 140, "sat": 0},
        ]}
        report = self.report(snapshot)
        ceiling = report["points"][2]
        self.assertTrue(ceiling["censored"])
        self.assertFalse(ceiling["usedInPercentFit"])
        self.assertFalse(ceiling["usedInOutputFit"])
        # And what the clock itself said is kept beside it rather than thrown
        # away: the two disagreeing is worth seeing.
        self.assertTrue(ceiling["clockUsed"])
        self.assertEqual(report["percentFit"]["count"], 2)
        self.assertEqual(report["outputFit"]["count"], 2)

    def test_censoring_follows_the_range_this_report_is_run_with(self):
        # Which points count as censored depends on where the ceiling is, so a
        # range given here rather than by the clock has to move it.
        snapshot = {"minPercent": 20, "maxPercent": 100, "slope": 16.0, "points": [
            {"used": True, "lux": 0.02, "percent": 30, "hue": 140, "sat": 0},
            {"used": True, "lux": 0.60, "percent": 45, "hue": 140, "sat": 0},
            {"used": True, "lux": 9.00, "percent": 60, "hue": 140, "sat": 0},
        ]}
        wide = self.report(snapshot)
        self.assertFalse(wide["points"][2]["censored"])
        narrow = self.report(snapshot, min_percent=20, max_percent=60)
        self.assertTrue(narrow["points"][2]["censored"])
        self.assertFalse(narrow["points"][2]["usedInPercentFit"])
        self.assertEqual(narrow["maxPercent"], 60)

    def test_an_unknown_colour_is_excluded_and_named_rather_than_guessed(self):
        snapshot = {"points": [dict(SNAPSHOT["points"][0]), dict(SNAPSHOT["points"][1]),
                               dict(SNAPSHOT["points"][2]),
                               {"used": True, "lux": 2.0, "percent": 70, "seconds": 5}]}
        report = self.report(snapshot)
        self.assertEqual(report["outputFit"]["count"], 3)
        self.assertEqual(report["percentFit"]["count"], 4)
        self.assertIsNone(report["points"][3]["outputResidual"])
        self.assertTrue(any("unknown colour" in w for w in report["warnings"]))

    def test_an_unknown_point_does_not_censor_a_known_one_out_of_the_fit(self):
        # Censoring and its "fewer than two left" fallback have to be decided
        # over the points that can actually be transformed. Counted over all of
        # them, an unknown point below the ceiling makes the ceiling point look
        # dispensable - and the output fit is then left with one point, or none
        # at all. The two fits have different populations, so they need
        # different censoring passes.
        snapshot = {"minPercent": 20, "maxPercent": 100, "slope": 16.0, "points": [
            {"used": True, "lux": 0.02, "percent": 30, "hue": 140, "sat": 0},
            {"used": True, "lux": 2.00, "percent": 70},               # unknown colour
            {"used": True, "lux": 9.00, "percent": 100, "hue": 140, "sat": 0},
        ]}
        report = self.report(snapshot)
        # The percent fit sees three points, censors the ceiling and keeps two.
        self.assertEqual(report["percentFit"]["count"], 2)
        # The output fit sees only the two it can transform; censoring the
        # ceiling would leave one, so the fallback keeps both - a poor line
        # beats no line, and one point is not a line at all.
        self.assertEqual(report["outputFit"]["count"], 2)
        self.assertTrue(report["outputFit"]["fitted"])

    def test_it_reports_a_residual_offset_per_colour(self):
        # Two points in one colour estimate one offset robustly. That is the
        # whole claim - not a surface over hue and saturation.
        report = self.report()
        white = [g for g in report["colours"] if g["sat"] == 0][0]
        self.assertEqual(white["count"], 3)
        self.assertIn("meanResidual", white)
        self.assertIn("spreadDecades", white)

    NEAR = {"points": [
        {"used": True, "lux": 1.00, "percent": 40, "hue": 140, "sat": 0},
        {"used": True, "lux": 1.30, "percent": 45, "hue": 140, "sat": 0}]}

    def test_without_spread_the_output_fit_is_unavailable_not_invented(self):
        # There is no slope to keep here. The clock's stored slope is in
        # percent per decade and this line is in decades of light per decade of
        # light; dividing one by a hundred is arithmetic, not a conversion, and
        # the number it produces has no source. So: no line, and say so.
        report = self.report(self.NEAR)
        self.assertFalse(report["outputFit"]["available"])
        self.assertIsNone(report["outputFit"].get("slope"))
        self.assertIn("spread", report["outputFit"]["reason"])
        self.assertTrue(any("spread" in w for w in report["warnings"]))
        # Nothing downstream may quietly carry on as if a line existed.
        self.assertEqual(report["curves"], [])
        for row in report["points"]:
            self.assertIsNone(row["outputCurve"])
            self.assertIsNone(row["outputResidual"])
            self.assertIsNone(row["predictedPercent"])
            # What each point emitted is still a fact and still shown.
            self.assertIsNotNone(row["logOutput"])

    def test_a_prior_slope_may_be_supplied_and_is_labelled_as_supplied(self):
        report = self.report(self.NEAR, output_prior_slope=0.42)
        self.assertTrue(report["outputFit"]["available"])
        self.assertFalse(report["outputFit"]["fitted"])
        self.assertTrue(report["outputFit"]["priorSlope"])
        self.assertAlmostEqual(report["outputFit"]["slope"], 0.42)
        self.assertIsNotNone(report["points"][0]["predictedPercent"])

    def test_a_supplied_prior_slope_has_to_be_a_usable_slope(self):
        for bad in (0.0, -0.3, float("nan")):
            with self.assertRaises(ValueError, msg=repr(bad)):
                self.report(self.NEAR, output_prior_slope=bad)

    def test_the_percent_fit_keeps_the_clock_slope_but_invents_none(self):
        # The clock's own slope is a real number and the firmware itself falls
        # back to it, so using it is not an invention - but a snapshot that
        # does not carry one leaves nothing to fall back to.
        with_slope = dict(self.NEAR, slope=16.0)
        report = self.report(with_slope)
        self.assertTrue(report["percentFit"]["available"])
        self.assertFalse(report["percentFit"]["fitted"])
        self.assertAlmostEqual(report["percentFit"]["slope"], 16.0)
        self.assertTrue(report["percentFit"]["priorSlope"])

        bare = self.report(self.NEAR)
        self.assertFalse(bare["percentFit"]["available"])
        self.assertIn("spread", bare["percentFit"]["reason"])

    def test_adequate_spread_still_produces_everything_it_did(self):
        report = self.report()
        self.assertTrue(report["percentFit"]["available"])
        self.assertTrue(report["outputFit"]["available"])
        self.assertTrue(report["outputFit"]["fitted"])
        self.assertFalse(report["outputFit"]["priorSlope"])
        self.assertTrue(report["curves"])
        self.assertIsNotNone(report["points"][0]["predictedPercent"])

    def test_it_predicts_percent_curves_for_the_colours_asked_about(self):
        report = self.report(colours=[(140, 0), (225, 100)])
        curves = {(c["hue"], c["sat"]): c for c in report["curves"]}
        self.assertIn((225, 100), curves)
        blue = curves[(225, 100)]
        # Over the observed lux range, and in the units the slider is in.
        self.assertEqual(len(blue["percent"]), len(blue["lux"]))
        self.assertTrue(all(20 <= p <= 100 for p in blue["percent"]))
        # Deep blue cannot reach a white-equivalent target at the bright end,
        # and that is exposed rather than smoothed away.
        self.assertTrue(any(blue["limited"]))
        self.assertTrue(any("cannot reach" in w for w in report["warnings"]))

    def test_an_assumed_drive_table_is_confessed(self):
        report = cl.compare(SNAPSHOT, drive=cl.DriveTable.proportional())
        self.assertTrue(report["driveAssumed"])
        self.assertTrue(any("drive" in w for w in report["warnings"]))


class CsvAndCliTest(unittest.TestCase):
    """The report as a file, and the command that produces it."""

