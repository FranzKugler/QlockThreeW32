"""The colour/output model, tested against the firmware it has to agree with.

Every number here is either copied from a source file in this repository or
generated by the pinned FastLED itself (`tests/golden/`). Nothing is an
ordinary HSV conversion: the clock writes `CRGB(CHSV(...))`, which is FastLED's
*rainbow* wheel, and a geometric HSV would be wrong in a way that looks right.
"""
