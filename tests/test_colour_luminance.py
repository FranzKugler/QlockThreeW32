class FastLedGoldenTest(unittest.TestCase):
    """Against FastLED 3.9.15 itself, not against a description of it.

    tests/golden/gen_fastled_vectors.cpp compiles the pinned library and prints
    what it answers; if this passes, the Python wheel *is* the clock's wheel.
    """

    def test_rainbow_wheel_matches_every_vector(self):
        for hue, sat, val, red, green, blue in GOLDEN["rainbow"]:
            self.assertEqual(
                cl.hsv2rgb_rainbow(hue, sat, val), (red, green, blue),
                "CHSV(%d, %d, %d)" % (hue, sat, val))

    def test_display_colour_matches_every_vector(self):
        # Through the clock's own 0..359 / 0..100 conversion as well, so the
        # test covers the whole path from what the owner set to what FastLED
        # writes.
        for degrees, percent, red, green, blue in GOLDEN["display"]:
            self.assertEqual(
                cl.display_rgb(degrees, percent), (red, green, blue),
                "hue %d deg, sat %d %%" % (degrees, percent))

    def test_gamma_matches_the_firmware_float_arithmetic(self):
        # The firmware computes this in `float` with `lroundf`; Python is
        # double with round-half-to-even. Over the whole domain they agree,
        # and this is what says so.
        for percent, drive in enumerate(GOLDEN["gamma"]):
            self.assertEqual(cl.gamma_scale(percent), drive, "percent %d" % percent)

    def test_channel_drive_matches_the_driver(self):
        for part, scaled, expected in GOLDEN["channelDrive"]:
            self.assertEqual(cl.channel_drive(part, scaled), expected,
                             "part %d at scale %d" % (part, scaled))

    def test_it_is_not_ordinary_hsv(self):
        # The one vector that would pass with geometric HSV is no test at all.
        # FastLED's rainbow puts "yellow" at (171, 170, 0) where geometric HSV
        # would give (255, 255, 0) - the wheel is deliberately not uniform, and
        # a yellow face is a third of the light an ordinary HSV would predict.
        self.assertEqual(cl.hsv2rgb_rainbow(64, 255, 255), (171, 170, 0))
        # And hue 255 is not hue 0: the wheel does not close on itself.
        self.assertEqual(cl.hsv2rgb_rainbow(255, 255, 255), (253, 0, 2))
